DROP TABLE IF EXISTS movimiento CASCADE;
DROP TABLE IF EXISTS cuenta CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;
DROP TABLE IF EXISTS persona CASCADE;

CREATE TABLE persona (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    genero          VARCHAR(20)  NOT NULL,
    edad            INTEGER      NOT NULL CHECK (edad BETWEEN 0 AND 120),
    identificacion  VARCHAR(20)  NOT NULL,
    direccion       VARCHAR(200) NOT NULL,
    telefono        VARCHAR(20)  NOT NULL,
    CONSTRAINT uk_persona_identificacion UNIQUE (identificacion)
);

CREATE TABLE cliente (
    persona_id  BIGINT       PRIMARY KEY,
    cliente_id  VARCHAR(30)  NOT NULL,
    contrasena  VARCHAR(100) NOT NULL,
    estado      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_cliente_cliente_id UNIQUE (cliente_id),
    CONSTRAINT fk_cliente_persona FOREIGN KEY (persona_id)
        REFERENCES persona (id) ON DELETE CASCADE
);

CREATE TABLE cuenta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_cuenta   VARCHAR(20)   NOT NULL,
    tipo_cuenta     VARCHAR(20)   NOT NULL,
    saldo_inicial   NUMERIC(15,2) NOT NULL CHECK (saldo_inicial >= 0),
    estado          BOOLEAN       NOT NULL DEFAULT TRUE,
    cliente_id      BIGINT        NOT NULL,
    CONSTRAINT uk_cuenta_numero UNIQUE (numero_cuenta),
    CONSTRAINT ck_cuenta_tipo CHECK (tipo_cuenta IN ('AHORRO', 'CORRIENTE')),
    CONSTRAINT fk_cuenta_cliente FOREIGN KEY (cliente_id)
        REFERENCES cliente (persona_id)
);

CREATE INDEX idx_cuenta_cliente ON cuenta (cliente_id);

CREATE TABLE movimiento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_movimiento  VARCHAR(20)   NOT NULL,
    valor            NUMERIC(15,2) NOT NULL,
    saldo            NUMERIC(15,2) NOT NULL CHECK (saldo >= 0),
    cuenta_id        BIGINT        NOT NULL,
    CONSTRAINT ck_movimiento_tipo CHECK (tipo_movimiento IN ('CREDITO', 'DEBITO')),
    CONSTRAINT ck_movimiento_signo CHECK (
        (tipo_movimiento = 'CREDITO' AND valor > 0) OR
        (tipo_movimiento = 'DEBITO'  AND valor < 0)
    ),
    CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (cuenta_id)
        REFERENCES cuenta (id)
);

CREATE INDEX idx_movimiento_cuenta_fecha ON movimiento (cuenta_id, fecha);

